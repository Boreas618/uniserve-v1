#!/bin/sh
# Build the Qwen3-MoE deployment's key list from every source that launches it.
#
# Three things launch a deployment and no one of them can name the others' work:
#
#   the model     `cargo run -p qwen3-moe --example keys` - layers, the MoE, the KV
#                 path. It cannot name `slot_commit`: no model calls it.
#   the sampler   `argmax`, `top_k`, `softmax`, `inverse_cdf`, the five gathers - the
#                 runner's sampling chain, which no model forward reaches.
#   the runner    `slot_commit`'s descriptors (`commit_descriptors`), which the epoch
#                 asks for because no model asks.
#
# A fixture holding one source builds clean and stops a run at the first operator it
# lacks. `37 of 37` proved the list and the store agreed, never that the list was
# complete.
#
# Usage:
#   tools/build_qwen3_fixture.sh <checkpoint root> <runner keys file> <out file> [<commit>]
#
# `NVFP4_BUCKETS` states the packed deployment's row buckets (default `1,15`): the packed
# product is compiled per row class, so that list is which class the list holds.
#
# `runner keys file` holds `operator<TAB>key` lines for the sampler and the commit,
# and it is required: a fixture without it is the list that stops a run. Two
# launches produce it, and neither is reachable from the model's enumeration:
#
#   sampler   cargo run -q -p ops --example qwen3_moe_keys
#             the rows whose operator is one of the ten sampler operators; that
#             example also prints the model's, which this script takes from the
#             checkpoint instead, so the two halves stay told apart.
#   commit    cargo run -q -p executor --example runner_keys -- \
#                 --rows 1,2,4,8 --tokens 128,512 --sampled true --vocabulary 151936
#
# The checked-in file is `notes/programs/qwen3-moe-runner-keys.txt`, whose header
# states both commands and the deployment values it was generated with.
set -eu

root=${1:?usage: build_qwen3_fixture.sh <checkpoint root> <runner keys file> <out file> [<commit>]}
runner_keys=${2:?the runner keys are a second source, not an option}
out=${3:?an output path}
commit=${4:-unknown}

# The packed product's row class is a deployment value, not a checkpoint one: `nn::layers::packed_rows`
# states the smallest declared class that holds a batch, so the buckets stated here decide which packed
# class a store built from this file can serve. It is an argument because a deployment with a larger
# bound states a class no row of this file covers.
buckets=${NVFP4_BUCKETS:-1,15}

if [ ! -f "$runner_keys" ]; then
    echo "no runner keys at $runner_keys: a fixture built without them stops a run" >&2
    echo "at the first runner-owned operator, and the store still reports N of N." >&2
    exit 1
fi

staging=$(mktemp -d)
trap 'rm -rf "$staging"' EXIT

model_keys="$staging/model.txt"
: >"$model_keys"

# The three configurations the deployment serves: a BF16 stack, an NVFP4 stack and an
# FP8 cache. The union is what one store must hold.
for config in "--cache bf16 --quantization bf16" \
              "--cache bf16 --quantization nvfp4 --buckets $buckets" \
              "--cache f8e4m3 --quantization bf16"; do
    # shellcheck disable=SC2086
    cargo run -q -p qwen3-moe --example keys -- --checkpoint "$root" $config 2>/dev/null \
        | grep -P '^\w+\t' >>"$model_keys" || true
done

model_rows=$(sort -u "$model_keys" | wc -l | tr -d ' ')
runner_rows=$(grep -cP '^\w+\t' "$runner_keys" || true)

{
    echo "# Qwen3-MoE deployment keys, generated by tools/build_qwen3_fixture.sh."
    echo "#"
    echo "# model:  $model_rows rows from the model's own enumeration over three configurations"
    echo "#         (bf16 stack, nvfp4 stack, f8e4m3 cache). The nvfp4 stack states its"
    echo "#         packed row buckets as $buckets, which is one packed class: a deployment"
    echo "#         whose bound is larger states a class no row here covers."
    echo "# runner: $runner_rows rows from the launches the executor makes - the sampler chain"
    echo "#         and slot_commit - which no model call reaches and no model walk states."
    echo "# commit: $commit"
    echo "#"
    echo "# A list short of any source above builds clean and stops a run at the first"
    echo "# missing operator. Both counts are part of the evidence, not decoration."
    sort -u "$model_keys" "$runner_keys" | grep -P '^\w+\t'
} >"$out"

total=$(grep -cP '^\w+\t' "$out" || true)
echo "$out: $model_rows model + $runner_rows runner = $total rows ($commit)"

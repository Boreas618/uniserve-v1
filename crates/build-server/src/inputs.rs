//! What a module is built from, and the digest that names it in the store.
//!
//! A module's bytes are determined by its package's files, by the compiler
//! that builds them and by the shared compile driver of the Build Server's
//! Python environment (`uniserve_build_server`: the Triton and CuTe DSL
//! drivers, the fetcher and the manifests of its pinned third-party sources).
//! An installed revision records the first two as [`Inputs`]: the digest of
//! the package's files, and the identity of the toolchain that builds them,
//! which carries the driver's digest ([`crate::Toolchains::identity`]). A
//! module's store path names [`Inputs::digest`], so a module is found only
//! where every one of those is what it was built from: a revision installed in
//! another package root under the same number, a driver or pin edited without
//! a reinstall, or a toolchain upgrade never reaches a module of other inputs.
//!
//! The record lives in the revision's directory as [`RECORD`], written by
//! `install` before the directory is published, so a revision and its record
//! appear together; a read-only package root mounted on another host carries
//! it to the hosts that serve the upstream's modules without a toolchain.

use std::fs;
use std::io;
use std::path::Path;

use serde::{Deserialize, Serialize};
use sha2::{Digest, Sha256};

use crate::{Error, Result};

/// The file of an installed revision that records its build inputs.
pub const RECORD: &str = ".inputs";

/// The directory Python writes a module's bytecode into beside its source.
///
/// Bytecode is derived from the sources and regenerated by the interpreter, so
/// it is no input of a build: an install does not copy it, and a digest skips
/// it, because a Python build runs in the installed copy and leaves its own
/// bytecode there.
pub const BYTECODE_CACHE: &str = "__pycache__";

/// The build inputs of one installed revision.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub struct Inputs {
    /// The SHA-256 of the package's files ([`crate::snapshot::files_digest`]),
    /// in hex.
    pub package: String,
    /// The toolchain that builds the package, as [`crate::Toolchains::identity`]
    /// states it: its kind and version, and the compile driver's digest.
    pub toolchain: String,
}

impl Inputs {
    /// The inputs of the package in `directory`, whose manifest is `manifest`,
    /// built by `toolchain`: the digest of what an installation of it holds
    /// ([`crate::snapshot::package_files`]).
    ///
    /// # Errors
    ///
    /// Fails when the package's files cannot be read.
    pub fn of(directory: &Path, manifest: &crate::Manifest, toolchain: String) -> Result<Inputs> {
        let files = crate::snapshot::package_files(directory, manifest)?;
        Ok(Inputs {
            package: crate::snapshot::files_digest(&files)?,
            toolchain,
        })
    }

    /// The digest a module of these inputs is stored under: the SHA-256 of the
    /// package digest and the toolchain identity, in hex.
    pub fn digest(&self) -> String {
        let mut hasher = Sha256::new();
        hasher.update(self.package.as_bytes());
        hasher.update([0]);
        hasher.update(self.toolchain.as_bytes());
        format!("{:x}", hasher.finalize())
    }

    /// The record of the revision in `directory`, which every installed
    /// revision holds.
    ///
    /// # Errors
    ///
    /// Fails when the record cannot be read or parsed.
    pub fn read(directory: &Path) -> Result<Inputs> {
        let path = directory.join(RECORD);
        let text = fs::read_to_string(&path).map_err(|error| {
            Error::Io(io::Error::new(
                error.kind(),
                format!("{}: {error}", path.display()),
            ))
        })?;
        toml::from_str(&text).map_err(|error| {
            Error::Io(io::Error::new(
                io::ErrorKind::InvalidData,
                format!("{}: {error}", path.display()),
            ))
        })
    }

    /// Writes this record into the revision directory `directory`, fsynced.
    ///
    /// # Errors
    ///
    /// Fails when the file cannot be written.
    pub fn write(&self, directory: &Path) -> Result<()> {
        let text = toml::to_string(self).map_err(|error| {
            Error::Io(io::Error::new(
                io::ErrorKind::InvalidData,
                error.to_string(),
            ))
        })?;
        let path = directory.join(RECORD);
        fs::write(&path, text)?;
        fs::File::open(&path)?.sync_all()?;
        Ok(())
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    /// A record reads back as written, and a module's digest changes with either input.
    #[test]
    fn a_record_reads_back_and_its_digest_names_both_inputs() {
        let directory = tempfile::tempdir().unwrap();
        let inputs = Inputs {
            package: "ab".repeat(32),
            toolchain: "triton 3.7.1; driver cd".to_owned(),
        };
        assert!(Inputs::read(directory.path()).is_err());
        inputs.write(directory.path()).unwrap();
        assert_eq!(Inputs::read(directory.path()).unwrap(), inputs);

        let other_toolchain = Inputs {
            toolchain: "triton 3.7.2; driver cd".to_owned(),
            ..inputs.clone()
        };
        let other_package = Inputs {
            package: "ef".repeat(32),
            ..inputs.clone()
        };
        assert_ne!(inputs.digest(), other_toolchain.digest());
        assert_ne!(inputs.digest(), other_package.digest());
        assert_eq!(inputs.digest().len(), 64);
    }
}

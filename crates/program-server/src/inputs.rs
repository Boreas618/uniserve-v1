//! What a module is built from, and the digest that names it in the store.
//!
//! A module's bytes are determined by its package's files, by the compiler
//! that builds them and by the shared compile driver of the Program Server's
//! Python environment (`uniserve_program_server`: the Triton and CuTe DSL
//! drivers, the fetcher and the manifests of its pinned third-party sources).
//! An installed revision records the first two as [`Inputs`]: the digest of
//! the package's files, and the identity of the toolchain that builds them,
//! which carries the driver's digest ([`crate::Toolchains::identity`]). A
//! module's store path names [`Inputs::digest`], so a module is found only
//! where every one of those is what it was built from: a revision installed in
//! another package root under the same number, a driver or pin edited without
//! a reinstall, or a toolchain upgrade never reaches a module of other inputs.
//!
//! The record lives in the revision's directory as [`RECORD`], written by
//! `install` before the directory is published, so a revision and its record
//! appear together; a read-only package root mounted on another host carries
//! it to the hosts that serve the upstream's modules without a toolchain.

use std::fs;
use std::io;
use std::path::Path;

use serde::{Deserialize, Serialize};
use sha2::{Digest, Sha256};

use crate::{Error, Result};

/// The file of an installed revision that records its build inputs.
pub const RECORD: &str = ".inputs";

/// The directory Python writes a module's bytecode into beside its source.
///
/// Bytecode is derived from the sources and regenerated by the interpreter, so
/// it is no input of a build: an install does not copy it, and a digest skips
/// it, because a Python build runs in the installed copy and leaves its own
/// bytecode there.
pub const BYTECODE_CACHE: &str = "__pycache__";

/// The build inputs of one installed revision.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub struct Inputs {
    /// The SHA-256 of the package's files ([`tree_digest`]), in hex.
    pub package: String,
    /// The toolchain that builds the package, as [`crate::Toolchains::identity`]
    /// states it: its kind and version, and the compile driver's digest.
    pub toolchain: String,
}

impl Inputs {
    /// The inputs of the package in `directory`, built by `toolchain`.
    ///
    /// # Errors
    ///
    /// Fails when the directory cannot be read.
    pub fn of(directory: &Path, toolchain: String) -> Result<Inputs> {
        Ok(Inputs {
            package: tree_digest(directory)?,
            toolchain,
        })
    }

    /// The digest a module of these inputs is stored under: the SHA-256 of the
    /// package digest and the toolchain identity, in hex.
    pub fn digest(&self) -> String {
        let mut hasher = Sha256::new();
        hasher.update(self.package.as_bytes());
        hasher.update([0]);
        hasher.update(self.toolchain.as_bytes());
        hex(&hasher.finalize())
    }

    /// The record of the revision in `directory`, or `None` when it has none.
    ///
    /// # Errors
    ///
    /// Fails when the record exists and cannot be read or parsed.
    pub fn read(directory: &Path) -> Result<Option<Inputs>> {
        let path = directory.join(RECORD);
        let text = match fs::read_to_string(&path) {
            Ok(text) => text,
            Err(error) if error.kind() == io::ErrorKind::NotFound => return Ok(None),
            Err(error) => return Err(Error::Io(error)),
        };
        toml::from_str(&text).map(Some).map_err(|error| {
            Error::Io(io::Error::new(
                io::ErrorKind::InvalidData,
                format!("{}: {error}", path.display()),
            ))
        })
    }

    /// Writes this record into the revision directory `directory`, fsynced.
    ///
    /// # Errors
    ///
    /// Fails when the file cannot be written.
    pub fn write(&self, directory: &Path) -> Result<()> {
        let text = toml::to_string(self).map_err(|error| {
            Error::Io(io::Error::new(
                io::ErrorKind::InvalidData,
                error.to_string(),
            ))
        })?;
        let path = directory.join(RECORD);
        fs::write(&path, text)?;
        fs::File::open(&path)?.sync_all()?;
        Ok(())
    }
}

/// The SHA-256 of a directory tree's files, in hex.
///
/// Every file is hashed with its path relative to `root`, in path order, so a
/// renamed or moved file changes the digest as a changed byte does. A symbolic
/// link counts as what it names, as an install copies it. Python bytecode
/// ([`BYTECODE_CACHE`]) and a revision's own record ([`RECORD`]) are not
/// inputs and are skipped.
///
/// # Errors
///
/// Fails when the tree cannot be read.
pub fn tree_digest(root: &Path) -> Result<String> {
    let mut hasher = Sha256::new();
    hash_tree(root, Path::new(""), &mut hasher)?;
    Ok(hex(&hasher.finalize()))
}

fn hash_tree(directory: &Path, prefix: &Path, hasher: &mut Sha256) -> Result<()> {
    let mut entries: Vec<_> = fs::read_dir(directory)?
        .map(|entry| entry.map(|entry| entry.file_name()))
        .collect::<io::Result<_>>()?;
    entries.sort();
    for name in entries {
        if name == BYTECODE_CACHE || (prefix.as_os_str().is_empty() && name == RECORD) {
            continue;
        }
        let path = directory.join(&name);
        let relative = prefix.join(&name);
        if fs::metadata(&path)?.is_dir() {
            hash_tree(&path, &relative, hasher)?;
            continue;
        }
        let bytes = fs::read(&path)?;
        // Each file is framed by its path and its length, so no two trees hash
        // one byte stream.
        hasher.update(relative.to_string_lossy().as_bytes());
        hasher.update([0]);
        hasher.update((bytes.len() as u64).to_le_bytes());
        hasher.update(&bytes);
    }
    Ok(())
}

fn hex(bytes: &[u8]) -> String {
    bytes.iter().map(|byte| format!("{byte:02x}")).collect()
}

#[cfg(test)]
mod tests {
    use super::*;

    fn tree(root: &Path, files: &[(&str, &str)]) {
        for (name, text) in files {
            let path = root.join(name);
            fs::create_dir_all(path.parent().unwrap()).unwrap();
            fs::write(path, text).unwrap();
        }
    }

    /// A changed byte, a renamed file and an added file each change a tree's digest; bytecode and
    /// the revision's record do not.
    #[test]
    fn a_tree_digest_follows_the_files_a_build_reads() {
        let directory = tempfile::tempdir().unwrap();
        let root = directory.path();
        tree(
            root,
            &[("package.toml", "op = 1\n"), ("src/kernel.py", "x = 1\n")],
        );
        let base = tree_digest(root).unwrap();

        tree(
            root,
            &[
                ("src/__pycache__/kernel.pyc", "bytecode"),
                (RECORD, "record"),
            ],
        );
        assert_eq!(tree_digest(root).unwrap(), base);

        tree(root, &[("src/kernel.py", "x = 2\n")]);
        let edited = tree_digest(root).unwrap();
        assert_ne!(edited, base);

        fs::rename(root.join("src/kernel.py"), root.join("src/other.py")).unwrap();
        assert_ne!(tree_digest(root).unwrap(), edited);

        tree(root, &[("src/kernel.py", "x = 2\n")]);
        assert_ne!(tree_digest(root).unwrap(), edited);
    }

    /// A record reads back as written, and a module's digest changes with either input.
    #[test]
    fn a_record_reads_back_and_its_digest_names_both_inputs() {
        let directory = tempfile::tempdir().unwrap();
        let inputs = Inputs {
            package: "ab".repeat(32),
            toolchain: "triton 3.7.1; driver cd".to_owned(),
        };
        assert_eq!(Inputs::read(directory.path()).unwrap(), None);
        inputs.write(directory.path()).unwrap();
        assert_eq!(
            Inputs::read(directory.path()).unwrap(),
            Some(inputs.clone())
        );

        let other_toolchain = Inputs {
            toolchain: "triton 3.7.2; driver cd".to_owned(),
            ..inputs.clone()
        };
        let other_package = Inputs {
            package: "ef".repeat(32),
            ..inputs.clone()
        };
        assert_ne!(inputs.digest(), other_toolchain.digest());
        assert_ne!(inputs.digest(), other_package.digest());
        assert_eq!(inputs.digest().len(), 64);
    }
}
